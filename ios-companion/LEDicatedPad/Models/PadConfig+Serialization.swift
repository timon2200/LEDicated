import Foundation

public extension PadConfig {
    /// Parses a dictionary from `/api/live/pads` or `/api/live/status` safely,
    /// preserving the exact MacBook Live Board configuration 1:1.
    static func fromServerDictionary(_ dict: [String: Any], index: Int, fallback: PadConfig) -> PadConfig {
        let key = (dict["key"] as? String)?.uppercased()
            ?? (index < padKeys.count ? padKeys[index] : fallback.key)

        let preset = (dict["preset"] as? String) ?? fallback.preset
        let mode = (dict["mode"] as? String) ?? fallback.mode
        let driver = (dict["driver"] as? String) ?? "none"
        let intensity = (dict["intensity"] as? NSNumber)?.doubleValue ?? fallback.intensity

        let paramsDict = dict["params"] as? [String: Any]
        let speed = (dict["speed"] as? NSNumber)?.doubleValue
            ?? (paramsDict?["speed"] as? NSNumber)?.doubleValue
            ?? 1.0

        let direction = (dict["direction"] as? String) ?? "ltr"
        let timing = (dict["timing"] as? String) ?? "beat"
        let motionMode = (dict["motionMode"] as? String) ?? "serial"
        let hitTravel = (dict["hitTravel"] as? String) ?? "full"
        let hitBeats = (dict["hitBeats"] as? NSNumber)?.doubleValue ?? 0.5

        let duration: Double = {
            if let d = (dict["duration"] as? NSNumber)?.doubleValue, d > 0 { return d }
            return max(0.2, min(3.0, hitBeats))
        }()

        // Color & White channel: server sends `color: [r, g, b, w]`
        var rgb: [Double] = [1, 1, 1]
        var whiteVal: Double = (dict["white"] as? NSNumber)?.doubleValue ?? 0.0
        if let rawColor = dict["color"] as? [Any], rawColor.count >= 3 {
            let r = (rawColor[0] as? NSNumber)?.doubleValue ?? 1.0
            let g = (rawColor[1] as? NSNumber)?.doubleValue ?? 1.0
            let b = (rawColor[2] as? NSNumber)?.doubleValue ?? 1.0
            rgb = [r, g, b]
            if rawColor.count >= 4, dict["white"] == nil {
                whiteVal = (rawColor[3] as? NSNumber)?.doubleValue ?? whiteVal
            }
        }

        var secondaryRgb: [Double]? = nil
        if let rawSec = dict["colorSecondary"] as? [Any], rawSec.count >= 3 {
            let r = (rawSec[0] as? NSNumber)?.doubleValue ?? rgb[0]
            let g = (rawSec[1] as? NSNumber)?.doubleValue ?? rgb[1]
            let b = (rawSec[2] as? NSNumber)?.doubleValue ?? rgb[2]
            secondaryRgb = [r, g, b]
        }

        let bars: [String] = {
            if let tStr = dict["targets"] as? String, tStr == "all" {
                return BarID.allRawIds
            }
            if let tArr = dict["targets"] as? [String], !tArr.isEmpty {
                return tArr
            }
            if let bArr = dict["bars"] as? [String], !bArr.isEmpty {
                return bArr
            }
            return BarID.allRawIds
        }()

        // Match the MacBook's Croatian preset labels unless the user gave a custom name
        let rawName = (dict["name"] as? String)?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        let autoGeneratedPattern = "\(preset.uppercased()) \(key.uppercased())"
        let presetLabel = EffectPreset(rawValue: preset)?.label ?? preset.capitalized
        let name: String = {
            if rawName.isEmpty || rawName.uppercased() == autoGeneratedPattern {
                return presetLabel
            }
            return rawName
        }()

        var strOpts: [String: String] = [:]
        var floorVal: Double? = nil
        var glowVal: Double? = nil
        if let pDict = paramsDict {
            for (k, v) in pDict {
                if let s = v as? String {
                    strOpts[k] = s
                } else if k == "floor", let n = (v as? NSNumber)?.doubleValue {
                    floorVal = n
                } else if k == "glow", let n = (v as? NSNumber)?.doubleValue {
                    glowVal = n
                }
            }
        }

        let params = PadParams(
            speed: speed,
            floor: floorVal,
            glow: glowVal,
            stringOptions: strOpts
        )

        return PadConfig(
            key: key,
            name: name,
            mode: mode,
            preset: preset,
            driver: driver,
            intensity: intensity,
            duration: duration,
            color: rgb,
            colorSecondary: secondaryRgb,
            white: whiteVal,
            bars: bars,
            params: params,
            direction: direction,
            timing: timing,
            motionMode: motionMode,
            hitTravel: hitTravel,
            hitBeats: hitBeats,
            isEmpty: false
        )
    }

    /// Converts pad back into the dictionary format expected by `server.mjs` (`syncServerPadSlot`).
    func toServerDictionary() -> [String: Any] {
        let r = color.count > 0 ? color[0] : 1.0
        let g = color.count > 1 ? color[1] : 1.0
        let b = color.count > 2 ? color[2] : 1.0
        var paramsOut: [String: Any] = ["speed": params.speed]
        for (k, v) in params.stringOptions {
            paramsOut[k] = v
        }
        if let f = params.floor { paramsOut["floor"] = f }
        if let gl = params.glow { paramsOut["glow"] = gl }

        var dict: [String: Any] = [
            "key": key,
            "name": name,
            "mode": mode,
            "preset": preset,
            "driver": driver,
            "intensity": intensity,
            "speed": params.speed,
            "duration": duration,
            "direction": direction,
            "timing": timing,
            "motionMode": motionMode,
            "hitTravel": hitTravel,
            "hitBeats": hitBeats,
            "white": white,
            "color": [r, g, b, white],
            "bars": bars.isEmpty ? BarID.allRawIds : bars,
            "targets": (bars.isEmpty || bars.count == 9) ? "all" : bars,
            "params": paramsOut
        ]
        if let sec = colorSecondary, sec.count >= 3 {
            dict["colorSecondary"] = sec
        }
        return dict
    }
}
